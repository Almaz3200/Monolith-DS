using Content.Client.UserInterface.Controls;
using Content.Shared._LuaM.HoloComms;
using Content.Shared.Holopad;
using Content.Shared.IdentityManagement;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._LuaM.HoloComms;

/// <summary>
/// The comms window of a shuttle console: the hologram of the other side down to the hips,
/// the last thing the one shown said, and the list of everybody the console can call.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class HoloCommsWindow : FancyWindow
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IUserInterfaceManager _uiManager = default!;

    /// <summary>
    /// The buttons wait a moment after the call changes, so a click meant for the old buttons does not hit the new ones.
    /// </summary>
    private static readonly TimeSpan ButtonLockTime = TimeSpan.FromSeconds(0.5);

    private static readonly Color LineColor = Color.FromHex("#E8C547");
    private static readonly Color RemoteColor = Color.FromHex("#4EC6E8");
    private static readonly Color SpeakerColor = Color.FromHex("#9FB3C8");

    public event Action<NetEntity>? OnCall;
    public event Action? OnAnswer;
    public event Action? OnHangUp;
    public event Action<bool>? OnDoNotDisturb;

    /// <summary>
    /// The window the comms always stay above.
    /// </summary>
    public Func<BaseWindow?>? AnchorWindow;

    private HoloCommsPhase _phase = HoloCommsPhase.Idle;
    private string? _remoteName;
    private string? _callerName;
    private NetEntity? _hologramNet;
    private EntityUid? _hologram;
    private EntityUid? _shownEntity;
    private TimeSpan _buttonsUnlockAt;
    private bool _buttonsLocked;

    public HoloCommsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        UseDeadSpaceMenuStyle();

        ContactsList.OnContactPicked += target => OnCall?.Invoke(target);
        DoNotDisturbButton.OnToggled += args => OnDoNotDisturb?.Invoke(args.Pressed);
        AnswerButton.OnPressed += _ => OnAnswer?.Invoke();
        DeclineButton.OnPressed += _ => OnHangUp?.Invoke();

        // Ends the call and closes the window
        EndButton.OnPressed += _ =>
        {
            if (_phase is HoloCommsPhase.Calling or HoloCommsPhase.Ringing or HoloCommsPhase.InCall)
                OnHangUp?.Invoke();

            Close();
        };

        UpdateTexts();
    }

    public void UpdateState(HoloCommsBoundUserInterfaceState state)
    {
        if (state.Phase != _phase)
        {
            // A new call starts with a clean screen
            if (state.Phase is HoloCommsPhase.Calling or HoloCommsPhase.Ringing &&
                _phase is HoloCommsPhase.Idle or HoloCommsPhase.Ending or HoloCommsPhase.Unpowered)
            {
                LastLinePanel.Visible = false;
            }

            _phase = state.Phase;
            _buttonsUnlockAt = _timing.RealTime + ButtonLockTime;
        }

        _remoteName = state.RemoteName;
        _callerName = state.CallerName;
        _hologramNet = state.Hologram;
        ResolveHologram();

        HologramView.ShowPlaceholder = _phase is HoloCommsPhase.Calling or HoloCommsPhase.Ringing or HoloCommsPhase.InCall;

        DoNotDisturbButton.Pressed = state.DoNotDisturb;

        // The contacts only come while the line is free, during a call the last ones stay to read
        if (_phase == HoloCommsPhase.Idle)
            ContactsList.SetContacts(state.Contacts);

        MainButtons.Visible = _phase != HoloCommsPhase.Ringing;
        RingingButtons.Visible = _phase == HoloCommsPhase.Ringing;

        UpdateTexts();
        UpdateButtons(true);
    }

    /// <summary>
    /// A line of the one shown on the hologram, it stays under their name until the next one.
    /// </summary>
    public void AddLine(HoloCommsLineMessage line)
    {
        var message = new FormattedMessage();

        if (line.Emote)
        {
            message.PushTag(new MarkupNode("italic", null, null));
            message.AddText(Loc.GetString("holo-comms-log-emote", ("name", line.Speaker), ("action", line.Text)));
            message.Pop();
        }
        else
        {
            message.PushColor(LineColor);
            message.AddText(line.Text);
            message.Pop();
        }

        LastLineLabel.SetMessage(message);
        LastLinePanel.Visible = true;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var now = _timing.RealTime;

        // Only until the hologram comes, after that it stays known
        if (_hologramNet != null && _hologram == null)
            ResolveHologram();

        UpdateShownEntity();

        if (_buttonsLocked && now >= _buttonsUnlockAt)
            UpdateButtons(false);

        KeepAboveAnchor();
    }

    /// <summary>
    /// The hologram is made with the call, the state of the window can come before it does.
    /// Until then there is no entity for it, it is looked up again every frame while the window is open.
    /// </summary>
    private void ResolveHologram()
    {
        _entManager.TryGetEntity(_hologramNet, out var hologram);
        if (hologram == _hologram)
            return;

        _hologram = hologram;
        HologramView.SetHologram(_hologram);
    }

    private void UpdateShownEntity()
    {
        EntityUid? shown = null;
        if (_hologram != null && _entManager.TryGetComponent<HolopadHologramComponent>(_hologram, out var hologram))
            shown = hologram.LinkedEntity;

        if (shown == _shownEntity)
            return;

        _shownEntity = shown;
        UpdateTexts();
    }

    private void UpdateTexts()
    {
        var remote = _phase switch
        {
            HoloCommsPhase.Calling or HoloCommsPhase.Ringing or HoloCommsPhase.InCall when _remoteName != null => _remoteName,
            HoloCommsPhase.Unpowered => Loc.GetString("holo-comms-remote-unpowered"),
            _ => Loc.GetString("holo-comms-remote-none"),
        };
        RemoteLabel.SetMessage(HeaderText(remote, RemoteColor, true));

        var speaker = _phase switch
        {
            HoloCommsPhase.Ringing when !string.IsNullOrEmpty(_callerName) => _callerName,
            HoloCommsPhase.InCall when _shownEntity != null && _entManager.EntityExists(_shownEntity) =>
                Identity.Name(_shownEntity.Value, _entManager),
            _ => string.Empty,
        };
        SpeakerLabel.SetMessage(HeaderText(speaker, SpeakerColor, false));
        SpeakerLabel.Visible = speaker.Length > 0;

        ScreenStatusLabel.Text = _phase switch
        {
            HoloCommsPhase.Unpowered => Loc.GetString("holo-comms-status-unpowered"),
            HoloCommsPhase.Calling => Loc.GetString("holo-comms-status-calling"),
            HoloCommsPhase.Ringing => Loc.GetString("holo-comms-status-ringing"),
            HoloCommsPhase.InCall when _shownEntity == null => Loc.GetString("holo-comms-status-nobody"),
            HoloCommsPhase.Ending => Loc.GetString("holo-comms-status-ended"),
            HoloCommsPhase.Idle => Loc.GetString("holo-comms-status-idle"),
            _ => string.Empty,
        };
    }

    private static FormattedMessage HeaderText(string text, Color color, bool bold)
    {
        var message = new FormattedMessage();
        if (bold)
            message.PushTag(new MarkupNode("bold", null, null));

        message.PushColor(color);
        message.AddText(text);
        message.Pop();

        if (bold)
            message.Pop();

        return message;
    }

    private void UpdateButtons(bool locked)
    {
        _buttonsLocked = locked && _timing.RealTime < _buttonsUnlockAt;

        var powered = _phase != HoloCommsPhase.Unpowered;
        ContactsList.SetLocked(_buttonsLocked || _phase != HoloCommsPhase.Idle);
        DoNotDisturbButton.Disabled = !powered;
        AnswerButton.Disabled = _buttonsLocked;
        DeclineButton.Disabled = _buttonsLocked;
        EndButton.Disabled = _buttonsLocked && _phase != HoloCommsPhase.Idle;
    }

    /// <summary>
    /// The console window must never cover the comms, clicking it brings it to the front, so the comms go right back over it.
    /// </summary>
    private void KeepAboveAnchor()
    {
        if (Parent == null || AnchorWindow?.Invoke() is not { IsOpen: true } anchor || anchor.Parent != Parent)
            return;

        if (anchor.GetPositionInParent() > GetPositionInParent())
            _uiManager.DeferAction(MoveToFront); // the window order can't change while the engine goes over them
    }
}
