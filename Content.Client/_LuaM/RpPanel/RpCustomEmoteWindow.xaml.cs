using System.Linq;
using Content.Shared._LuaM.RpPanel;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Audio.Systems;
using Robust.Shared.Player;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._LuaM.RpPanel;

[GenerateTypedNameReferences]
public sealed partial class RpCustomEmoteWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    private static readonly RpInteractionKind[] Kinds = Enum.GetValues<RpInteractionKind>();

    private readonly SpriteSystem _sprite;
    private readonly SharedAudioSystem _audio;
    private readonly List<RpInteractionCategoryPrototype> _categories;
    private readonly List<RpCustomSoundPrototype> _sounds;
    private EntityUid? _preview;

    public RpCustomEmote? Editing { get; private set; }

    public event Action<RpCustomEmote?, RpCustomEmote>? OnSave;
    public event Action<RpCustomEmote>? OnDelete;

    public RpCustomEmoteWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _entManager.System<SpriteSystem>();
        _audio = _entManager.System<SharedAudioSystem>();

        NameInput.IsValid = text => text.Length <= RpCustomEmote.MaxNameLength;
        MessageInput.IsValid = text => text.Length <= RpCustomEmote.MaxMessageLength;

        var modeGroup = new ButtonGroup(false);
        TargetModeButton.Group = modeGroup;
        SelfModeButton.Group = modeGroup;
        TargetModeButton.OnPressed += _ => UpdateMode();
        SelfModeButton.OnPressed += _ => UpdateMode();

        _categories = _prototypeManager.EnumeratePrototypes<RpInteractionCategoryPrototype>()
            .OrderBy(RpPanelWindow.GetCategoryLocName)
            .ToList();
        for (var i = 0; i < _categories.Count; i++)
            CategorySelector.AddItem(RpPanelWindow.GetCategoryLocName(_categories[i]), i);

        for (var i = 0; i < Kinds.Length; i++)
            KindSelector.AddItem(Loc.GetString($"rp-panel-kind-{RpPanelWindow.ToKebabCase(Kinds[i].ToString())}"), i);

        _sounds = _prototypeManager.EnumeratePrototypes<RpCustomSoundPrototype>()
            .OrderBy(GetSoundName)
            .ToList();
        SoundSelector.AddItem(Loc.GetString("rp-custom-emote-sound-none"), -1);
        for (var i = 0; i < _sounds.Count; i++)
            SoundSelector.AddItem(GetSoundName(_sounds[i]), i);

        CategorySelector.OnItemSelected += args =>
        {
            CategorySelector.SelectId(args.Id);
            UpdateIcon();
        };
        KindSelector.OnItemSelected += args => KindSelector.SelectId(args.Id);
        SoundSelector.OnItemSelected += args => SoundSelector.SelectId(args.Id);
        SoundSelector.OnPreview += PreviewSound;
        OnClose += () => _preview = _audio.Stop(_preview);

        CloseOnSecondClick(CategorySelector);
        CloseOnSecondClick(KindSelector);
        CloseOnSecondClick(SoundSelector);

        NameInput.OnTextChanged += _ => UpdateSaveButton();
        MessageInput.OnTextChanged += _ => UpdateSaveButton();

        SaveButton.OnPressed += _ => Save();
        CancelButton.OnPressed += _ => Close();
        DeleteButton.OnPressed += _ =>
        {
            if (Editing != null)
                OnDelete?.Invoke(Editing);

            Close();
        };
    }

    public void SetEmote(RpCustomEmote? emote)
    {
        Editing = emote;
        Title = Loc.GetString(emote == null ? "rp-custom-emote-title-new" : "rp-custom-emote-title-edit");
        DeleteButton.Visible = emote != null;

        NameInput.Text = emote?.Name ?? string.Empty;
        MessageInput.Text = emote?.Message ?? string.Empty;
        TargetModeButton.Pressed = emote is not { Self: true };
        SelfModeButton.Pressed = emote is { Self: true };

        var category = emote == null ? -1 : _categories.FindIndex(c => c.ID == emote.Category.Id);
        CategorySelector.SelectId(Math.Max(category, 0));
        KindSelector.SelectId(Math.Max(Array.IndexOf(Kinds, emote?.Kind ?? RpInteractionKind.Soft), 0));
        SoundSelector.SelectId(emote?.Sound is { } sound ? _sounds.FindIndex(s => s.ID == sound.Id) : -1);

        UpdateIcon();
        UpdateMode();
        UpdateSaveButton();
    }

    private void Save()
    {
        if (_categories.Count == 0)
            return;

        var emote = new RpCustomEmote
        {
            Name = RpCustomEmote.Sanitize(NameInput.Text, RpCustomEmote.MaxNameLength),
            Category = _categories[CategorySelector.SelectedId].ID,
            Kind = Kinds[KindSelector.SelectedId],
            Sound = SoundSelector.SelectedId >= 0 ? _sounds[SoundSelector.SelectedId].ID : null,
            Message = RpCustomEmote.Sanitize(MessageInput.Text, RpCustomEmote.MaxMessageLength),
            Self = SelfModeButton.Pressed,
            Favorite = Editing?.Favorite ?? false,
        };

        if (emote.Name.Length == 0 || emote.Message.Length == 0)
            return;

        OnSave?.Invoke(Editing, emote);
        Close();
    }

    private void UpdateSaveButton()
    {
        SaveButton.Disabled = string.IsNullOrWhiteSpace(NameInput.Text) ||
                              string.IsNullOrWhiteSpace(MessageInput.Text);
    }

    private void UpdateMode()
    {
        var self = SelfModeButton.Pressed;
        MessageInput.PlaceHolder = Loc.GetString(self
            ? "rp-custom-emote-self-message-placeholder"
            : "rp-custom-emote-message-placeholder");
        HintLabel.Text = Loc.GetString(self ? "rp-custom-emote-hint-self" : "rp-custom-emote-hint");
    }

    private void UpdateIcon()
    {
        IconPreview.Texture = _categories.Count > 0
            ? _sprite.Frame0(_categories[CategorySelector.SelectedId].Icon)
            : null;
    }

    private void CloseOnSecondClick(OptionButton button)
    {
        if (button.OptionsScroll.Parent is not Popup popup)
            return;

        uint closedFrame = 0;
        var keepClosed = false;

        popup.OnPopupHide += () => closedFrame = _timing.CurFrame;
        button.OnButtonDown += _ => keepClosed = closedFrame == _timing.CurFrame;
        button.OnPressed += _ =>
        {
            if (keepClosed)
                popup.Close();

            keepClosed = false;
        };
    }

    private void PreviewSound(int id)
    {
        if (id < 0 || id >= _sounds.Count)
            return;

        _audio.Stop(_preview);
        _preview = _audio.PlayGlobal(_sounds[id].Sound, Filter.Local(), false)?.Entity;
    }

    private static string GetSoundName(RpCustomSoundPrototype sound)
    {
        return Loc.GetString($"rp-panel-custom-sound-{RpPanelWindow.ToKebabCase(sound.ID)}-name");
    }
}
